export const generateMathProblem = (level: string): MathProblem => {
  const isYoung = isYoungCat(level);
  let maxAdd = 5;
  let allowMinus = false;
  if (level === 'baby') {
    maxAdd = 4;
    allowMinus = false;
  } else if (level === 'kitten') {
    maxAdd = 6;
    allowMinus = false;
  } else if (level === 'teen') {
    maxAdd = 10;
    allowMinus = true;
  } else if (level === 'adult') {
    maxAdd = 15;
    allowMinus = true;
  } else {
    maxAdd = 20;
    allowMinus = true;
  }

  const isMinus = allowMinus && Math.random() > 0.5;
  if (isMinus) {
    const result = Math.floor(Math.random() * (maxAdd === 20 ? 10 : 6)) + 1;
    const b = Math.floor(Math.random() * 5) + 1;
    const a = result + b;
    const wordAnswer = NUMBER_WORDS[result] || String(result);
    const numericAnswer = String(result);
    return {
      q: `${a} - ${b}`,
      result,
      numericAnswer,
      wordAnswer,
      answer: isYoung ? numericAnswer : wordAnswer
    };
  } else {
    let a = Math.floor(Math.random() * (maxAdd - 1)) + 1;
    let b = Math.floor(Math.random() * (maxAdd - a)) + 1;
    if (level === 'baby' && a + b > 5) {
      a = 2;
      b = 2;
    }
    const sum = a + b;
    const wordAnswer = NUMBER_WORDS[sum] || String(sum);
    const numericAnswer = String(sum);
    return {
      q: `${a} + ${b}`,
      result: sum,
      numericAnswer,
      wordAnswer,
      answer: isYoung ? numericAnswer : wordAnswer
    };
  }
};

